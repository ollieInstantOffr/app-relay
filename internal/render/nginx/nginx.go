func parsePorts(s string) (lo, hi int, err error) {
	s = strings.TrimSpace(s)
	a, b, isRange := strings.Cut(s, "-")
	lo, err = strconv.Atoi(strings.TrimSpace(a))
	if err != nil {
		return 0, 0, fmt.Errorf("invalid port %q", s)
	}
	hi = lo
	if isRange {
		if hi, err = strconv.Atoi(strings.TrimSpace(b)); err != nil {
			return 0, 0, fmt.Errorf("invalid port range %q", s)
		}
	}
	if lo < 1 || hi > 65535 || hi < lo {
		return 0, 0, fmt.Errorf("invalid port range %q", s)
	}
	return lo, hi, nil
}

func hostPort(host string, port string) string {
	if ip := net.ParseIP(host); ip != nil && ip.To4() == nil {
		return "[" + host + "]:" + port
	}
	return host + ":" + port
}

func (r *renderer) streamFile(s *model.Stream) string {
	w := &writer{}
	w.raw(header)
	w.l("# Stream %s (id %s, %s)", comment(s.Name), comment(s.ID), comment(orDefault(s.Protocol, "tcp")))
	lo, hi, err := parsePorts(s.ListenPorts)
	if err != nil {
		r.fail("stream %s: %v", s.Name, err)
		w.l("# skipped: %s", comment(err.Error()))
		return w.String()
	}
	fwdHost := strings.TrimSpace(s.ForwardHost)
	flo, fhi := lo, hi
	if s.BackendID != "" {
		fe := r.backendFrontend(s.BackendID)
		if fe == "" {
			name := s.BackendID
			if b := r.backends[s.BackendID]; b != nil {
				name = b.Name
			}
			r.fail("stream %s: backend %s has no enabled TCP frontend bound to 127.0.0.1", s.Name, name)
			w.l("# skipped: backend %s has no enabled TCP frontend on 127.0.0.1", comment(name))
			return w.String()
		}
		h, p, _ := net.SplitHostPort(fe)
		fwdHost = h
		flo, _ = strconv.Atoi(p)
		fhi = flo
		w.l("# via HAProxy backend %s (frontend %s)", comment(s.BackendID), fe)
	} else if strings.TrimSpace(s.ForwardPorts) != "" {
		if flo, fhi, err = parsePorts(s.ForwardPorts); err != nil {
			r.fail("stream %s: forward %v", s.Name, err)
			w.l("# skipped: forward %s", comment(err.Error()))
			return w.String()
		}
	}
	if fwdHost == "" {
		r.fail("stream %s: forward host is empty", s.Name)
		w.l("# skipped: forward host is empty")
		return w.String()
	}
	if flo != fhi && fhi-flo != hi-lo {
		r.fail("stream %s: listen range %s and forward range %s differ in size", s.Name, s.ListenPorts, s.ForwardPorts)
		w.l("# skipped: port ranges differ in size")
		return w.String()
	}

	protos := []string{""}
	switch s.Protocol {
	case "udp":
		protos = []string{" udp"}
	case "both":
		protos = []string{"", " udp"}
	}
	addr := strings.TrimSpace(s.ListenAddress)
	listen := func(ports string) {
		for _, p := range protos {
			if addr == "" {
				w.l("listen %s%s;", ports, p)
			} else {
				w.l("listen %s%s;", hostPort(addr, ports), p)
			}
		}
	}
	common := func() {
		w.l("set $relay_stream_id %s;", q(s.ID))
		if t := strings.TrimSpace(s.IdleTimeout); t != "" && timeRe.MatchString(t) {
			w.l("proxy_timeout %s;", t)
		} else {
			w.l("proxy_timeout 10m;")
		}
		w.l("proxy_connect_timeout 10s;")
		if s.ProxyProtocol {
			w.l("proxy_protocol on;")
		}
	}
	ports := strconv.Itoa(lo)
	if hi != lo {
		ports = fmt.Sprintf("%d-%d", lo, hi)
	}
	isIP := net.ParseIP(fwdHost) != nil
	sid := safeID(s.ID)

	switch {
	case flo == fhi: // everything to one port
		w.open("server")
		listen(ports)
		common()
		w.l("proxy_pass %s;", hostPort(fwdHost, strconv.Itoa(flo)))
		w.close()
	case isIP && flo == lo: // same ports 1:1
		w.open("server")
		listen(ports)
		common()
		w.l("proxy_pass %s;", hostPort(fwdHost, "$server_port"))
		w.close()
	case isIP: // shifted range 1:1
		if hi-lo > 5000 {
			r.fail("stream %s: port range too large", s.Name)
			return w.String()
		}
		w.open("map $server_port $relay_stream_port_%s", sid)
		for p := lo; p <= hi; p++ {
			w.l("%d %d;", p, flo+(p-lo))
		}
		w.close()
		w.open("server")
		listen(ports)
		common()
		w.l("proxy_pass %s;", hostPort(fwdHost, "$relay_stream_port_"+sid))
		w.close()
	default: // hostname: one server per port keeps the config resolver-free
		if hi-lo > 1000 {
			r.fail("stream %s: port ranges to a hostname are limited to 1000 ports", s.Name)
			return w.String()
		}
		for p := lo; p <= hi; p++ {
			w.open("server")
			listen(strconv.Itoa(p))
			common()
			w.l("proxy_pass %s;", hostPort(fwdHost, strconv.Itoa(flo+(p-lo))))
			w.close()
		}
	}
	return w.String()
}

var timeRe = regexp.MustCompile(`^[0-9]+(ms|s|m|h|d)?$`)

// backendFrontend returns the 127.0.0.1 bind of the first enabled TCP
// frontend whose default backend is backendID.
func (r *renderer) backendFrontend(backendID string) string {
	fes := append([]model.Frontend(nil), r.snap.Frontends...)
	sort.SliceStable(fes, func(i, j int) bool { return fes[i].CreatedAt.Before(fes[j].CreatedAt) })
	for _, f := range fes {
		if !f.Enabled || f.Mode != "tcp" || f.DefaultBackendID != backendID {
			continue
		}
		h, p, err := net.SplitHostPort(strings.TrimSpace(f.Bind))
		if err != nil || h != "127.0.0.1" {
			continue
		}
		if _, err := strconv.Atoi(p); err != nil {
			continue
		}
		return net.JoinHostPort(h, p)
	}
	return ""
}

// ---------------------------------------------------------------- htpasswd

func htpasswd(al *model.AccessList) string {
	users := append([]model.BasicAuthUser(nil), al.BasicAuth.Users...)
	sort.SliceStable(users, func(i, j int) bool { return users[i].Username < users[j].Username })
	var b strings.Builder
	b.WriteString("# " + comment(al.Name) + "\n")
	for _, u := range users {
		name := strings.TrimSpace(u.Username)
		if name == "" || u.PasswordHash == "" || strings.ContainsAny(name, ":\n") {
			continue
		}
		b.WriteString(name + ":" + strings.TrimSpace(u.PasswordHash) + "\n")
	}
	return b.String()
}

// ---------------------------------------------------------------- error & maintenance pages

// errorPageFiles renders Relay's error pages and each host's maintenance page.
func (r *renderer) errorPageFiles(hosts []*model.ProxyHost) map[string]string {
	out := map[string]string{}
	set := r.snap.ErrorPages.WithDefaults()
	if set.Enabled {
		for _, code := range render.ErrorPageCodes {
			key := fmt.Sprint(code)
			out["errors/"+key+".html"] = render.ErrorPageHTML(set, key, nil)
		}
	}
	for _, h := range hosts {
		if h.Maintenance.Enabled {
			out["errors/maintenance-"+safeID(h.ID)+".html"] = render.ErrorPageHTML(set, "maintenance", &h.Maintenance)
		}
	}
	return out
}

// errorPages renders the error_page directives of a host; it reports whether
// any were written (then the server needs the internal errors location).
func (r *renderer) errorPages(w *writer, h *model.ProxyHost) bool {
	on := r.snap.ErrorPages.Enabled
	if !on && !h.Maintenance.Enabled {
		return false
	}
	if on {
		for _, code := range render.ErrorPageCodes {
			if code == 503 && h.Maintenance.Enabled {
				continue
			}
			w.l("error_page %d %s%d.html;", code, render.ErrorsPath, code)
		}
	}
	if h.Maintenance.Enabled {
		w.l("error_page 503 %smaintenance-%s.html;", render.ErrorsPath, safeID(h.ID))
	}
	return true
}

// maintenance answers a location with 503 while the host is in maintenance
// (the Relay login location keeps working; ACME has its own location).
func (r *renderer) maintenance(w *writer, h *model.ProxyHost, l hostLocation) {
	if !h.Maintenance.Enabled || l.ID == render.PortalLocationID {
		return
	}
	if r.lists[h.Maintenance.BypassAccessListID] != nil {
		w.open("if ($relay_maint_%s)", safeID(h.ID))
		w.l("return 503;")
		w.close()
		return
	}
	w.l("return 503;")
}

// geoFromList renders an access list as an nginx geo map: allowed networks
// get allowed, denied ones denied; "all" sets the default.
func (r *renderer) geoFromList(w *writer, name string, al *model.AccessList, allowed, denied string) {
	w.open("geo %s", name)
	def := denied
	for _, rule := range al.Rules {
		cidr := strings.TrimSpace(rule.CIDR)
		if strings.EqualFold(cidr, "all") {
			if rule.Action == "allow" {
				def = allowed
			} else {
				def = denied
			}
			continue
		}
		if !validCIDR(cidr) {
			continue
		}
		if rule.Action == "allow" {
			w.l("%s %s;", cidr, allowed)
		} else {
			w.l("%s %s;", cidr, denied)
		}
	}
	w.l("default %s;", def)
	w.close()
}
