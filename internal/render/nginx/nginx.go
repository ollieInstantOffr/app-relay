type redirectGroup struct {
	domains   []string
	redirects []*model.Redirect
}

// hostDomains maps domains served by enabled proxy hosts to the host.
func (r *renderer) hostDomains() map[string]*model.ProxyHost {
	out := map[string]*model.ProxyHost{}
	for _, h := range r.enabledHosts() {
		for _, d := range h.Domains {
			out[strings.ToLower(strings.TrimSpace(d))] = h
		}
	}
	return out
}

func isWholeDomain(rd *model.Redirect) bool {
	p := strings.TrimSpace(rd.FromPath)
	return p == "" || p == "/"
}

func (r *renderer) enabledRedirects() []*model.Redirect {
	var out []*model.Redirect
	for i := range r.snap.Redirects {
		rd := &r.snap.Redirects[i]
		if rd.Enabled && len(rd.Domains) > 0 && strings.TrimSpace(rd.To) != "" {
			out = append(out, rd)
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Domains[0] != out[j].Domains[0] {
			return out[i].Domains[0] < out[j].Domains[0]
		}
		if len(out[i].FromPath) != len(out[j].FromPath) {
			return len(out[i].FromPath) > len(out[j].FromPath)
		}
		return out[i].ID < out[j].ID
	})
	return out
}

// redirectGroups groups redirects that need their own server block by domain set.
func (r *renderer) redirectGroups() []redirectGroup {
	hostDomains := r.hostDomains()
	idx := map[string]int{}
	var groups []redirectGroup
	for _, rd := range r.enabledRedirects() {
		domains := normDomains(rd.Domains)
		served := false
		for _, d := range domains {
			if hostDomains[d] != nil {
				served = true
			}
		}
		if served {
			continue // rendered inside the proxy host (path redirects) or skipped
		}
		key := strings.Join(domains, " ")
		i, ok := idx[key]
		if !ok {
			i = len(groups)
			idx[key] = i
			groups = append(groups, redirectGroup{domains: domains})
		}
		groups[i].redirects = append(groups[i].redirects, rd)
	}
	return groups
}

func normDomains(ds []string) []string {
	out := []string{}
	for _, d := range ds {
		d = strings.ToLower(strings.TrimSpace(d))
		if d != "" {
			out = append(out, d)
		}
	}
	sort.Strings(out)
	return out
}

func redirectCode(c int) int {
	switch c {
	case 301, 302, 307, 308:
		return c
	}
	return 301
}

func (r *renderer) redirectFile(g redirectGroup) string {
	w := &writer{}
	w.raw(header)
	var cert *model.Certificate
	certID := ""
	forceHTTPS := false
	for _, rd := range g.redirects {
		w.l("# Redirect %s%s → %s (%d, id %s)", comment(strings.Join(rd.Domains, ", ")), comment(rd.FromPath), comment(rd.To), redirectCode(rd.Code), comment(rd.ID))
		if cert == nil && rd.CertificateID != "" {
			if c, why := r.usableCert(rd.CertificateID); c != nil {
				cert, certID = c, rd.CertificateID
			} else {
				w.l("# %s: serving HTTP only", comment(why))
			}
		}
		if rd.ForceHTTPS {
			forceHTTPS = true
		}
	}
	names := serverNames(g.domains)
	if cert != nil && forceHTTPS {
		w.open("server")
		r.listenHTTP(w, false)
		w.l("server_name %s;", names)
		w.l("set $relay_host_id \"\";")
		r.blocked(w)
		w.l("include snippets/acme-challenge.conf;")
		w.open("location /")
		w.l("return 301 %s;", r.httpsRedirect())
		w.close()
		w.close()
		w.l("")
	}
	w.open("server")
	if cert == nil || !forceHTTPS {
		r.listenHTTP(w, false)
	}
	if cert != nil {
		r.listenHTTPS(w, false, false)
	}
	w.l("server_name %s;", names)
	w.l("set $relay_host_id \"\";")
	r.blocked(w)
	if cert != nil {
		r.tlsDirectives(w, certID, cert, r.cipherProfile(""), true)
	}
	if cert == nil || !forceHTTPS {
		w.l("include snippets/acme-challenge.conf;")
	}
	whole := false
	for _, rd := range g.redirects {
		w.l("")
		if isWholeDomain(rd) {
			if whole {
				continue
			}
			whole = true
			w.open("location /")
			w.l("return %d %s;", redirectCode(rd.Code), q(redirectTarget(rd.To, rd.KeepPath, "$request_uri")))
			w.close()
			continue
		}
		r.pathRedirect(w, rd)
	}
	if !whole {
		w.l("")
		w.open("location /")
		w.l("return 404;")
		w.close()
	}
	w.close()
	return w.String()
}

func redirectTarget(to string, keep bool, suffix string) string {
	to = strings.TrimSpace(to)
	if !keep {
		return to
	}
	return strings.TrimRight(to, "/") + suffix
}

func (r *renderer) pathRedirect(w *writer, rd *model.Redirect) {
	from := strings.TrimRight(normPath(rd.FromPath), "/")
	re := "^" + regexp.QuoteMeta(from) + "(?<relay_rest>/.*)?$"
	w.open("location ~ %s", q(re))
	if rd.KeepPath {
		w.l("return %d %s;", redirectCode(rd.Code), q(redirectTarget(rd.To, true, "$relay_rest$is_args$args")))
	} else {
		w.l("return %d %s;", redirectCode(rd.Code), q(strings.TrimSpace(rd.To)))
	}
	w.close()
}

// injectRedirects renders path redirects for domains served by host h.
func (r *renderer) injectRedirects(w *writer, h *model.ProxyHost) {
	domains := map[string]bool{}
	for _, d := range h.Domains {
		domains[strings.ToLower(strings.TrimSpace(d))] = true
	}
	for _, rd := range r.enabledRedirects() {
		match := false
		for _, d := range rd.Domains {
			if domains[strings.ToLower(strings.TrimSpace(d))] {
				match = true
			}
		}
		if !match {
			continue
		}
		w.l("")
		if isWholeDomain(rd) {
			w.l("# redirect %s → %s skipped: the domain is served by this proxy host", comment(first(rd.Domains)), comment(rd.To))
			continue
		}
		w.l("# Redirect %s → %s", comment(rd.FromPath), comment(rd.To))
		r.pathRedirect(w, rd)
	}
}

