func (r *renderer) globalConf(hosts []*model.ProxyHost) string {
	w := &writer{}
	w.raw(header)
	w.l("# Global deny list (Logs → Block IP). Every server returns 403 for these clients.")
	w.open("geo $relay_blocked")
	w.l("default 0;")
	entries := append([]model.BlockEntry(nil), r.snap.Blocklist.Entries...)
	sort.SliceStable(entries, func(i, j int) bool { return entries[i].CIDR < entries[j].CIDR })
	seen := map[string]bool{}
	for _, e := range entries {
		cidr := strings.TrimSpace(e.CIDR)
		if !validCIDR(cidr) || seen[cidr] {
			if !seen[cidr] {
				w.l("# skipped invalid entry %s", comment(cidr))
			}
			continue
		}
		seen[cidr] = true
		w.l("%s 1;", cidr)
	}
	w.close()

	// GeoIP2 country lookup, shared by all geo-blocked hosts.
	geoHosts := []*model.ProxyHost{}
	for _, h := range hosts {
		if h.GeoBlock.Enabled && len(h.GeoBlock.AllowCountries) > 0 {
			geoHosts = append(geoHosts, h)
		}
	}
	if len(geoHosts) > 0 {
		w.l("")
		if r.geoAvailable() {
			w.open("geoip2 %s", q(r.env.GeoIPCountry))
			w.l("auto_reload 60m;")
			w.l("$relay_geo_country country iso_code;")
			w.close()
		} else {
			w.l("# Geo-blocking is configured on %d host(s) but skipped: %s", len(geoHosts), r.geoUnavailableReason())
		}
	}

	for _, h := range sortedByID(hosts) {
		sid := safeID(h.ID)
		if h.Maintenance.Enabled {
			if al := r.lists[h.Maintenance.BypassAccessListID]; al != nil {
				w.l("")
				w.l("# Maintenance for %s: 1 = show the maintenance page, 0 = bypass (access list %s)", comment(h.Domains[0]), comment(al.Name))
				r.geoFromList(w, "$relay_maint_"+sid, al, "0", "1")
			}
		}
		if h.RateLimit.Enabled && h.RateLimit.RequestsPerSecond > 0 {
			w.l("")
			w.l("# Rate limit for %s", comment(h.Domains[0]))
			key := "$binary_remote_addr"
			if al := r.lists[h.RateLimit.ExemptAccessListID]; al != nil {
				w.open("geo $relay_rl_exempt_%s", sid)
				def := "0"
				for _, rule := range al.Rules {
					cidr := strings.TrimSpace(rule.CIDR)
					if strings.EqualFold(cidr, "all") {
						if rule.Action == "allow" {
							def = "1"
						}
						continue
					}
					if !validCIDR(cidr) {
						continue
					}
					if rule.Action == "allow" {
						w.l("%s 1;", cidr)
					} else {
						w.l("%s 0;", cidr)
					}
				}
				w.l("default %s;", def)
				w.close()
				w.open("map $relay_rl_exempt_%s $relay_rl_key_%s", sid, sid)
				w.l("1 \"\";")
				w.l("default $binary_remote_addr;")
				w.close()
				key = "$relay_rl_key_" + sid
			}
			w.l("limit_req_zone %s zone=relay_rl_%s:10m rate=%dr/s;", key, sid, h.RateLimit.RequestsPerSecond)
		}
		if h.GeoBlock.Enabled && len(h.GeoBlock.AllowCountries) > 0 && r.geoAvailable() {
			w.l("")
			w.l("# Countries allowed for %s (unknown/private addresses are allowed)", comment(h.Domains[0]))
			w.open("map $relay_geo_country $relay_geo_allow_%s", sid)
			w.l("default 0;")
			w.l("\"\" 1;")
			countries := append([]string(nil), h.GeoBlock.AllowCountries...)
			sort.Strings(countries)
			for _, c := range countries {
				c = strings.ToUpper(strings.TrimSpace(c))
				if len(c) == 2 {
					w.l("%s 1;", c)
				}
			}
			w.close()
		}
	}
	return w.String()
}

func sortedByID(hosts []*model.ProxyHost) []*model.ProxyHost {
	out := append([]*model.ProxyHost(nil), hosts...)
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func (r *renderer) geoAvailable() bool { return r.mod("geoip2") && r.env.GeoIPCountry != "" }

func (r *renderer) geoUnavailableReason() string {
	if !r.mod("geoip2") {
		return "the nginx geoip2 module is not available"
	}
	return "no GeoLite2-Country database found"
}

func validCIDR(s string) bool {
	if _, _, err := net.ParseCIDR(s); err == nil {
		return true
	}
	return net.ParseIP(s) != nil
}

// ---------------------------------------------------------------- TLS helpers

// usableCert returns the certificate when it has been issued (NotAfter set,
// PEM files written). Status is not used: a certificate whose renewal failed
// keeps serving its existing files; pending certificates get no TLS yet.
func (r *renderer) usableCert(id string) (*model.Certificate, string) {
	if id == "" {
		return nil, ""
	}
	c := r.certs[id]
	if c == nil {
		return nil, "certificate " + id + " does not exist"
	}
	if c.NotAfter != nil && !c.NotAfter.IsZero() {
		return c, ""
	}
	if c.Status != "" && c.Status != model.CertStatusValid {
		return nil, fmt.Sprintf("certificate %s has not been issued yet (%s)", c.Name, c.Status)
	}
	return nil, fmt.Sprintf("certificate %s has not been issued yet", c.Name)
}

func (r *renderer) cipherProfile(host string) string {
	for _, p := range []string{host, r.snap.TLS.CipherProfile} {
		if _, ok := tlsProfiles[p]; ok {
			return p
		}
	}
	return "intermediate"
}

func (r *renderer) hstsHeader(mode string) string {
	h := r.snap.TLS.HSTS
	on := h.Enabled
	switch mode {
	case "on":
		on = true
	case "off":
		on = false
	}
	if !on {
		return ""
	}
	age := h.MaxAgeSeconds
	if age <= 0 {
		age = 15768000
	}
	v := "max-age=" + strconv.Itoa(age)
	if h.IncludeSubdomains {
		v += "; includeSubDomains"
	}
	if h.Preload {
		v += "; preload"
	}
	return v
}

func (r *renderer) http3For(h *model.ProxyHost) bool {
	on := r.snap.General.HTTP3
	if h.HTTP3 != nil {
		on = *h.HTTP3
	}
	return on && r.mod("http_v3")
}

// quicEnabled reports whether any TLS server listens on QUIC (then the
// default server carries the single `reuseport` listen).
func (r *renderer) quicEnabled() bool {
	if !r.mod("http_v3") {
		return false
	}
	for _, h := range r.enabledHosts() {
		if c, _ := r.usableCert(h.CertificateID); c != nil && r.http3For(h) {
			return true
		}
	}
	return false
}

func (r *renderer) listenHTTP(w *writer, def bool) {
	suffix := ""
	if def {
		suffix = " default_server"
	}
	w.l("listen %d%s;", r.httpPort, suffix)
	if r.mod("ipv6") {
		w.l("listen [::]:%d%s;", r.httpPort, suffix)
	}
}

func (r *renderer) listenHTTPS(w *writer, def, quic bool) {
	suffix := ""
	if def {
		suffix = " default_server"
	}
	w.l("listen %d ssl%s;", r.httpsPort, suffix)
	if r.mod("ipv6") {
		w.l("listen [::]:%d ssl%s;", r.httpsPort, suffix)
	}
	if quic {
		reuse := ""
		if def {
			reuse = " reuseport"
		}
		w.l("listen %d quic%s%s;", r.httpsPort, reuse, suffix)
		if r.mod("ipv6") {
			w.l("listen [::]:%d quic%s%s;", r.httpsPort, reuse, suffix)
		}
	}
}

func (r *renderer) tlsDirectives(w *writer, certID string, c *model.Certificate, profile string, http2 bool) {
	if http2 {
		w.l("http2 on;")
	}
	var full, key string
	if c == nil {
		full, key = r.env.DefaultCertPaths()
	} else {
		full, key = r.env.CertPaths(certID)
	}
	w.l("ssl_certificate %s;", q(full))
	w.l("ssl_certificate_key %s;", q(key))
	w.l("include snippets/tls-%s.conf;", profile)
	if c != nil && r.snap.TLS.OCSPStapling && c.Provider == model.CertCustom {
		w.l("ssl_stapling on;")
		w.l("ssl_stapling_verify on;")
	}
}

func (r *renderer) blocked(w *writer) {
	w.open("if ($relay_blocked)")
	w.l("return 403;")
	w.close()
}

// ---------------------------------------------------------------- default server

const notFoundPage = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>404 Not Found</title></head><body style="margin:0;height:100vh;display:flex;align-items:center;justify-content:center;font:14px system-ui,sans-serif;color:#666;background:#fafaf9">404 · Not found</body></html>`

func (r *renderer) defaultConf() string {
	w := &writer{}
	w.raw(header)
	dh := r.snap.DefaultHost
	w.l("# Default server: requests for unknown domains or bare IPs (action: %s).", comment(orDefault(dh.Action, "close")))
	w.open("server")
	r.listenHTTP(w, true)
	r.listenHTTPS(w, true, r.quicEnabled())
	w.l("server_name _;")
	w.l("set $relay_host_id \"\";")
	r.blocked(w)
	cert, why := r.usableCert(dh.CertificateID)
	if dh.CertificateID != "" && cert == nil {
		w.l("# %s: using the self-signed placeholder", comment(why))
	}
	r.tlsDirectives(w, dh.CertificateID, cert, r.cipherProfile(""), true)
	w.l("")
	w.l("include snippets/acme-challenge.conf;")
	w.l("")
	switch dh.Action {
	case "404":
		w.open("location /")
		w.l("default_type text/html;")
		w.l("return 404 '%s';", notFoundPage)
		w.close()
	case "redirect":
		if strings.TrimSpace(dh.RedirectTo) == "" {
			w.l("# redirect target missing: closing the connection instead")
			w.open("location /")
			w.l("return 444;")
			w.close()
		} else {
			w.open("location /")
			w.l("return 302 %s;", q(strings.TrimSpace(dh.RedirectTo)))
			w.close()
		}
	case "host":
		h := r.hosts[dh.HostID]
		if h == nil || !h.Enabled {
			w.l("# default host %s is missing or disabled: closing the connection instead", comment(dh.HostID))
			w.open("location /")
			w.l("return 444;")
			w.close()
		} else {
			w.l("# Serving proxy host %s", comment(first(h.Domains)))
			r.hostBody(w, h, false)
		}
	default:
		w.open("location /")
		w.l("return 444;")
		w.close()
	}
	w.close()

	w.l("")
	w.l("# Local stub_status endpoint for Relay's metrics collector.")
	w.open("server")
	w.l("listen %s;", StubStatusAddr)
	w.l("server_name _;")
	w.l("set $relay_host_id \"\";")
	w.l("access_log off;")
	w.open("location = /stub_status")
	w.l("stub_status;")
	w.close()
	w.open("location /")
	w.l("return 404;")
	w.close()
	w.close()
	return w.String()
}

func orDefault(s, def string) string {
	if s == "" {
		return def
	}
	return s
}

func first(ss []string) string {
	if len(ss) == 0 {
		return ""
	}
	return ss[0]
}

// ---------------------------------------------------------------- proxy hosts

func (r *renderer) hostFile(h *model.ProxyHost) string {
	w := &writer{}
	w.raw(header)
	w.l("# Proxy host %s (id %s)", comment(strings.Join(h.Domains, ", ")), comment(h.ID))
	names := serverNames(h.Domains)
	cert, why := r.usableCert(h.CertificateID)
	if h.CertificateID != "" && cert == nil {
		w.l("# %s: serving HTTP only until it is valid", comment(why))
	}
	if cert != nil && h.ForceHTTPS {
		w.open("server")
		r.listenHTTP(w, false)
		w.l("server_name %s;", names)
		w.l("set $relay_host_id %s;", q(h.ID))
		r.blocked(w)
		w.l("include snippets/acme-challenge.conf;")
		w.open("location /")
		w.l("return 301 %s;", r.httpsRedirect())
		w.close()
		w.close()
		w.l("")
	}
	w.open("server")
	if cert == nil || !h.ForceHTTPS {
		r.listenHTTP(w, false)
	}
	quic := cert != nil && r.http3For(h)
	if cert != nil {
		r.listenHTTPS(w, false, quic)
	}
	w.l("server_name %s;", names)
	w.l("set $relay_host_id %s;", q(h.ID))
	if cert != nil {
		r.tlsDirectives(w, h.CertificateID, cert, r.cipherProfile(h.CipherProfile), h.HTTP2)
		if v := r.hstsHeader(h.HSTS); v != "" {
			w.l("add_header Strict-Transport-Security %s always;", q(v))
		}
		if quic {
			w.l("add_header Alt-Svc 'h3=\":%d\"; ma=86400' always;", r.httpsPort)
		}
	}
	if cert == nil || !h.ForceHTTPS {
		w.l("include snippets/acme-challenge.conf;")
	}
	r.hostBody(w, h, true)
	w.close()
	return w.String()
}

func (r *renderer) httpsRedirect() string {
	if r.httpsPort == 443 {
		return "https://$host$request_uri"
	}
	return fmt.Sprintf("https://$host:%d$request_uri", r.httpsPort)
}

func serverNames(domains []string) string {
	out := make([]string, 0, len(domains))
	for _, d := range domains {
		d = strings.ToLower(strings.TrimSpace(d))
		if d != "" {
			out = append(out, q(d))
		}
	}
	if len(out) == 0 {
		return "_"
	}
	return strings.Join(out, " ")
}

// hostBody renders everything inside a host's server block after listen /
// server_name / TLS: protections, auth, locations and the custom snippet.
func (r *renderer) hostBody(w *writer, h *model.ProxyHost, custom bool) {
	sid := safeID(h.ID)
	if custom { // the default server already emitted the blocklist check
		r.blocked(w)
	}
	if h.GeoBlock.Enabled && len(h.GeoBlock.AllowCountries) > 0 {
		if r.geoAvailable() {
			w.open("if ($relay_geo_allow_%s = 0)", sid)
			w.l("return 403;")
			w.close()
		} else {
			w.l("# geo-block skipped: %s", r.geoUnavailableReason())
		}
	}
	if h.BlockExploits {
		w.l("include snippets/block-exploits.conf;")
	}
	if h.NoIndex {
		w.l("add_header X-Robots-Tag \"noindex, nofollow\" always;")
	}
	if s := strings.TrimSpace(h.MaxBodySize); s != "" && validSize(s) {
		w.l("client_max_body_size %s;", s)
	}
	if h.ProxyReadTimeout > 0 {
		w.l("proxy_read_timeout %ds;", h.ProxyReadTimeout)
	}
	if h.ProxySendTimeout > 0 {
		w.l("proxy_send_timeout %ds;", h.ProxySendTimeout)
	}
	if h.RateLimit.Enabled && h.RateLimit.RequestsPerSecond > 0 {
		burst := h.RateLimit.Burst
		if burst < 0 {
			burst = 0
		}
		w.l("limit_req zone=relay_rl_%s burst=%d nodelay;", sid, burst)
		w.l("limit_req_status 429;")
	}
	if usesHTTPS(h) {
		w.l("proxy_ssl_server_name on;")
		if h.UpstreamTLSVerify {
			w.l("proxy_ssl_verify on;")
			w.l("proxy_ssl_verify_depth 3;")
			w.l("proxy_ssl_trusted_certificate %s;", caBundle)
		} else {
			w.l("proxy_ssl_verify off;")
		}
	}

	if r.errorPages(w, h) {
		w.open("location ^~ %s", render.ErrorsPath)
		w.l("internal;")
		w.l("alias %s;", q(strings.TrimRight(r.env.ConfDir, "/")+"/errors/"))
		w.close()
	}

	fa := r.forwardAuth(h)
	if fa {
		w.l("")
		w.l("# Forward auth (%s)", comment(orDefault(h.ForwardAuth.Provider, "custom")))
		w.open("location = %s", authLocation)
		w.l("internal;")
		w.l("proxy_pass %s;", q(strings.TrimSpace(h.ForwardAuth.VerifyURL)))
		w.l("proxy_pass_request_body off;")
		w.l("proxy_http_version 1.1;")
		w.l("proxy_set_header Content-Length \"\";")
		w.l("proxy_set_header X-Original-URL $scheme://$http_host$request_uri;")
		w.l("proxy_set_header X-Original-Method $request_method;")
		w.l("proxy_set_header X-Forwarded-Method $request_method;")
		w.l("proxy_set_header X-Forwarded-Proto $scheme;")
		w.l("proxy_set_header X-Forwarded-Host $http_host;")
		w.l("proxy_set_header X-Forwarded-Uri $request_uri;")
		w.l("proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
		w.l("proxy_set_header X-Real-IP $remote_addr;")
		if strings.HasPrefix(strings.ToLower(h.ForwardAuth.VerifyURL), "https://") {
			w.l("proxy_ssl_server_name on;")
		}
		w.close()
		if s := strings.TrimSpace(h.ForwardAuth.SignInURL); s != "" {
			sep := "?"
			if strings.Contains(s, "?") {
				sep = "&"
			}
			w.open("location @relay_signin")
			w.l("return 302 %s;", q(s+sep+"rd=$scheme://$http_host$request_uri"))
			w.close()
		}
	}

	// Locations: user-defined, longest prefix first; "/" always present.
	locs := r.hostLocations(h)
	for _, loc := range locs {
		w.l("")
		r.location(w, h, loc)
	}

	r.injectRedirects(w, h)

	if custom && strings.TrimSpace(h.CustomNginx) != "" {
		w.l("")
		w.l("# Custom nginx snippet")
		w.raw(h.CustomNginx)
	}
}

func usesHTTPS(h *model.ProxyHost) bool {
	if strings.EqualFold(h.Upstream.Scheme, "https") {
		return true
	}
	for _, l := range h.Locations {
		if l.Kind == model.LocationProxy && strings.EqualFold(l.Upstream.Scheme, "https") {
			return true
		}
	}
	return false
}

var sizeRe = regexp.MustCompile(`^[0-9]+[kKmMgG]?$`)

func validSize(s string) bool { return sizeRe.MatchString(s) }

func (r *renderer) forwardAuth(h *model.ProxyHost) bool {
	if !h.ForwardAuth.Enabled || strings.TrimSpace(h.ForwardAuth.VerifyURL) == "" {
		return false
	}
	if len(r.env.Modules) > 0 && !r.mod("auth_request") {
		r.fail("host %s uses forward auth, but nginx lacks the auth_request module", first(h.Domains))
		return false
	}
	return true
}

const acmePath = "/.well-known/acme-challenge/"

// hostLocations returns the host's locations (deduplicated, longest path
// first) with a default "/" when missing, plus "/.well-known/" without
// forward auth when SkipWellKnown is set.
type hostLocation struct {
	model.Location
	skipForwardAuth bool
}

func (r *renderer) hostLocations(h *model.ProxyHost) []hostLocation {
	seen := map[string]bool{acmePath: true}
	out := []hostLocation{}
	for _, l := range h.Locations {
		p := normPath(l.Path)
		if p == "" || seen[p] {
			continue
		}
		seen[p] = true
		l.Path = p
		out = append(out, hostLocation{Location: l})
	}
	if !seen["/"] {
		out = append(out, hostLocation{Location: model.Location{ID: "default", Path: "/", Kind: model.LocationSame, Websockets: h.Websockets}})
	}
	if h.ForwardAuth.Enabled && h.ForwardAuth.SkipWellKnown && !seen["/.well-known/"] {
		out = append(out, hostLocation{Location: model.Location{ID: "well-known", Path: "/.well-known/", Kind: model.LocationSame, Websockets: h.Websockets}, skipForwardAuth: true})
	}
	sort.SliceStable(out, func(i, j int) bool {
		if len(out[i].Path) != len(out[j].Path) {
			return len(out[i].Path) > len(out[j].Path)
		}
		return out[i].Path < out[j].Path
	})
	return out
}

func normPath(p string) string {
	p = strings.TrimSpace(p)
	if p == "" {
		return ""
	}
	if !strings.HasPrefix(p, "/") {
		p = "/" + p
	}
	return p
}

var staticExt = `\.(?:css|js|mjs|map|png|jpe?g|gif|ico|svg|webp|avif|bmp|woff2?|ttf|otf|eot|mp4|webm|ogg|mp3|wav|pdf)$`

func (r *renderer) location(w *writer, h *model.ProxyHost, l hostLocation) {
	w.open("location %s", q(l.Path))
	r.maintenance(w, h, l)
	if l.Kind == model.LocationDeny {
		w.l("return 403;")
		w.close()
		return
	}
	up := h.Upstream
	if l.Kind == model.LocationProxy {
		up = l.Upstream
	}
	websockets := l.Websockets
	if l.Path == "/" && l.ID == "default" {
		websockets = h.Websockets
	}
	r.access(w, h, l)
	rewrite := rewriteFor(l.Path, up.Path, l.StripPrefix)
	if rewrite != "" {
		w.raw(rewrite)
	}
	w.l("include snippets/proxy-headers.conf;")
	if websockets {
		w.l("proxy_set_header Upgrade $http_upgrade;")
		w.l("proxy_set_header Connection $connection_upgrade;")
	}
	if r.forwardAuthActive(h, l) {
		if h.ForwardAuth.PassRemoteUser {
			w.l("proxy_set_header Remote-User $relay_remote_user;")
			w.l("proxy_set_header Remote-Email $relay_remote_email;")
			w.l("proxy_set_header Remote-Name $relay_remote_name;")
		}
		if h.ForwardAuth.PassRemoteGroups {
			w.l("proxy_set_header Remote-Groups $relay_remote_groups;")
		}
	}
	for _, hd := range l.Headers {
		if !headerNameRe.MatchString(hd.Name) {
			continue
		}
		w.l("proxy_set_header %s %s;", hd.Name, q(hd.Value))
	}
	if h.CacheAssets || l.Cache {
		w.open("location ~* %s", q(staticExt))
		r.maintenance(w, h, l)
		w.l("proxy_cache relay_assets;")
		w.l("proxy_cache_valid 200 301 302 30d;")
		w.l("proxy_cache_use_stale error timeout updating http_500 http_502 http_503 http_504;")
		w.l("proxy_cache_lock on;")
		w.l("expires 30d;")
		if rewrite != "" {
			w.raw(rewrite)
		}
		w.l("proxy_pass %s;", upstreamURL(up))
		w.close()
	}
	w.l("proxy_pass %s;", upstreamURL(up))
	w.close()
}

var headerNameRe = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func (r *renderer) forwardAuthActive(h *model.ProxyHost, l hostLocation) bool {
	return !l.NoAuth && !l.skipForwardAuth && h.ForwardAuth.Enabled && strings.TrimSpace(h.ForwardAuth.VerifyURL) != "" &&
		(len(r.env.Modules) == 0 || r.mod("auth_request"))
}

// access renders the access list and forward-auth directives of a location.
func (r *renderer) access(w *writer, h *model.ProxyHost, l hostLocation) {
	if l.NoAuth {
		w.l("# no access list or forward auth for this path")
		return
	}
	listID := h.AccessListID
	if l.AccessListID != "" {
		listID = l.AccessListID
	}
	if listID != "" {
		al := r.lists[listID]
		if al == nil {
			w.l("# access list %s no longer exists: denying all", comment(listID))
			w.l("deny all;")
		} else {
			r.accessList(w, al)
		}
	}
	if r.forwardAuthActive(h, l) {
		w.l("auth_request %s;", authLocation)
		if h.ForwardAuth.PassRemoteUser {
			w.l("auth_request_set $relay_remote_user $upstream_http_remote_user;")
			w.l("auth_request_set $relay_remote_email $upstream_http_remote_email;")
			w.l("auth_request_set $relay_remote_name $upstream_http_remote_name;")
		}
		if h.ForwardAuth.PassRemoteGroups {
			w.l("auth_request_set $relay_remote_groups $upstream_http_remote_groups;")
		}
		if strings.TrimSpace(h.ForwardAuth.SignInURL) != "" {
			w.l("error_page 401 = @relay_signin;")
			// A location's own error_page stops the server's from applying.
			r.errorPages(w, h)
		}
	}
}

func (r *renderer) accessList(w *writer, al *model.AccessList) {
	w.l("# access list %s", comment(al.Name))
	hasRules := false
	lastAll := false
	anyAllow := false
	for _, rule := range al.Rules {
		cidr := strings.TrimSpace(rule.CIDR)
		action := "deny"
		if rule.Action == "allow" {
			action = "allow"
		}
		if strings.EqualFold(cidr, "all") {
			w.l("%s all;", action)
			hasRules, lastAll = true, true
			break
		}
		if !validCIDR(cidr) {
			w.l("# skipped invalid rule %s", comment(cidr))
			continue
		}
		w.l("%s %s;", action, cidr)
		hasRules = true
		if action == "allow" {
			anyAllow = true
		}
	}
	if hasRules && anyAllow && !lastAll {
		w.l("deny all;")
	}
	basic := al.BasicAuth.Enabled
	if basic {
		w.l("auth_basic %s;", q(orDefault(al.BasicAuth.Realm, "Restricted")))
		w.l("auth_basic_user_file htpasswd/%s;", safeID(al.ID))
	}
	if hasRules && basic {
		if al.SatisfyAny {
			w.l("satisfy any;")
		} else {
			w.l("satisfy all;")
		}
	}
}

func rewriteFor(locPath, upPath string, strip bool) string {
	base := strings.TrimRight(strings.TrimSpace(upPath), "/")
	if base != "" && !strings.HasPrefix(base, "/") {
		base = "/" + base
	}
	if strip && locPath != "/" {
		prefix := strings.TrimRight(locPath, "/")
		return fmt.Sprintf("rewrite %s %s break;", q("^"+regexp.QuoteMeta(prefix)+"/?(.*)$"), q(base+"/$1"))
	}
	if base != "" {
		return fmt.Sprintf("rewrite ^(.*)$ %s break;", q(base+"$1"))
	}
	return ""
}

func upstreamURL(u model.Upstream) string {
	scheme := strings.ToLower(u.Scheme)
	if scheme != "https" {
		scheme = "http"
	}
	host := strings.TrimSpace(u.Host)
	if ip := net.ParseIP(host); ip != nil && ip.To4() == nil {
		host = "[" + host + "]"
	}
	if u.Port > 0 {
		host += ":" + strconv.Itoa(u.Port)
	}
	return scheme + "://" + host
}

