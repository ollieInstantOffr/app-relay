// Render produces every nginx file (nginx.conf, conf.d/…, htpasswd/…).
func Render(snap *model.Snapshot, env render.Env) (agent.Files, error) {
	r := newRenderer(snap, env)
	return r.all()
}

// RenderHost renders the server block(s) of one proxy host (which may be a
// draft not yet saved in snap) for previews.
func RenderHost(snap *model.Snapshot, host *model.ProxyHost, env render.Env) (string, error) {
	s := *snap
	s.Hosts = replaceHost(snap.Hosts, host)
	r := newRenderer(&s, env)
	h := *host
	h.Enabled = true
	out := r.hostFile(&h)
	return out, r.err()
}

// RenderStream renders the stream server block(s) of one stream for previews.
func RenderStream(snap *model.Snapshot, stream *model.Stream, env render.Env) (string, error) {
	r := newRenderer(snap, env)
	st := *stream
	st.Enabled = true
	out := r.streamFile(&st)
	return out, r.err()
}

// WithHost returns a copy of snap where host replaces the entity with the
// same id (or is appended when new). Used to validate drafts.
func WithHost(snap *model.Snapshot, host *model.ProxyHost) *model.Snapshot {
	s := *snap
	s.Hosts = replaceHost(snap.Hosts, host)
	return &s
}

// WithStream is WithHost for streams.
func WithStream(snap *model.Snapshot, stream *model.Stream) *model.Snapshot {
	s := *snap
	s.Streams = make([]model.Stream, 0, len(snap.Streams)+1)
	found := false
	for _, x := range snap.Streams {
		if stream.ID != "" && x.ID == stream.ID {
			s.Streams = append(s.Streams, *stream)
			found = true
			continue
		}
		s.Streams = append(s.Streams, x)
	}
	if !found {
		s.Streams = append(s.Streams, *stream)
	}
	return &s
}

func replaceHost(hosts []model.ProxyHost, host *model.ProxyHost) []model.ProxyHost {
	out := make([]model.ProxyHost, 0, len(hosts)+1)
	found := false
	for _, x := range hosts {
		if host.ID != "" && x.ID == host.ID {
			out = append(out, *host)
			found = true
			continue
		}
		out = append(out, x)
	}
	if !found {
		out = append(out, *host)
	}
	return out
}

// ---------------------------------------------------------------- renderer

const header = "# Generated by Relay — do not edit. Changes are overwritten on the next apply.\n"

// Paths inside the engine container (Alpine nginx packages).
const (
	mimeTypes    = "/etc/nginx/mime.types"
	pidFile      = "/run/nginx/nginx.pid"
	cacheDir     = "/var/cache/nginx/relay"
	caBundle     = "/etc/ssl/certs/ca-certificates.crt"
	authLocation = "/.relay/auth"
)

// StubStatusAddr is where the local stub_status server listens (the apply
// service sets it from $RELAY_NGINX_STATUS_PORT; the nginx agent's bootstrap
// config uses the same variable).
var StubStatusAddr = "127.0.0.1:18080"

type renderer struct {
	snap      *model.Snapshot
	env       render.Env
	certs     map[string]*model.Certificate
	lists     map[string]*model.AccessList
	hosts     map[string]*model.ProxyHost
	backends  map[string]*model.Backend
	httpPort  int
	httpsPort int
	errs      []string
}

func newRenderer(snap *model.Snapshot, env render.Env) *renderer {
	r := &renderer{
		snap: snap, env: env,
		certs: map[string]*model.Certificate{}, lists: map[string]*model.AccessList{},
		hosts: map[string]*model.ProxyHost{}, backends: map[string]*model.Backend{},
		httpPort: snap.General.HTTPPort, httpsPort: snap.General.HTTPSPort,
	}
	if r.httpPort <= 0 {
		r.httpPort = 80
	}
	if r.httpsPort <= 0 {
		r.httpsPort = 443
	}
	if r.env.Modules == nil {
		r.env.Modules = map[string]bool{}
	}
	for i := range snap.Certificates {
		r.certs[snap.Certificates[i].ID] = &snap.Certificates[i]
	}
	for i := range snap.AccessLists {
		r.lists[snap.AccessLists[i].ID] = &snap.AccessLists[i]
	}
	for i := range snap.Hosts {
		r.hosts[snap.Hosts[i].ID] = &snap.Hosts[i]
	}
	for i := range snap.Backends {
		r.backends[snap.Backends[i].ID] = &snap.Backends[i]
	}
	return r
}

func (r *renderer) fail(format string, args ...any) {
	r.errs = append(r.errs, fmt.Sprintf(format, args...))
}

func (r *renderer) err() error {
	if len(r.errs) == 0 {
		return nil
	}
	return fmt.Errorf("nginx render: %s", strings.Join(r.errs, "; "))
}

func (r *renderer) mod(name string) bool { return r.env.Modules[name] }

// enabledHosts returns enabled hosts sorted by first domain, then id.
func (r *renderer) enabledHosts() []*model.ProxyHost {
	var out []*model.ProxyHost
	for i := range r.snap.Hosts {
		if h := &r.snap.Hosts[i]; h.Enabled && len(h.Domains) > 0 {
			out = append(out, h)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Domains[0] != out[j].Domains[0] {
			return out[i].Domains[0] < out[j].Domains[0]
		}
		return out[i].ID < out[j].ID
	})
	return out
}

func (r *renderer) all() (agent.Files, error) {
	files := agent.Files{}
	hosts := r.enabledHosts()

	files["snippets/proxy-headers.conf"] = proxyHeadersSnippet
	files["snippets/acme-challenge.conf"] = r.acmeSnippet()
	files["snippets/block-exploits.conf"] = blockExploitsSnippet
	for _, p := range []string{"modern", "intermediate", "old"} {
		files["snippets/tls-"+p+".conf"] = header + tlsProfiles[p]
	}
	files["conf.d/00-global.conf"] = r.globalConf(hosts)
	files["conf.d/10-default.conf"] = r.defaultConf()
	for name, body := range r.errorPageFiles(hosts) {
		files[name] = body
	}

	used := map[string]bool{}
	for _, h := range hosts {
		name := uniqueName("conf.d/hosts/", h.Domains[0], h.ID, used)
		files[name] = r.hostFile(h)
	}
	for _, g := range r.redirectGroups() {
		name := uniqueName("conf.d/redirects/", g.domains[0], g.redirects[0].ID, used)
		files[name] = r.redirectFile(g)
	}
	streamServers := 0
	if r.mod("stream") {
		streams := r.enabledStreams()
		for _, s := range streams {
			name := uniqueName("streams/", s.Name, s.ID, used)
			content := r.streamFile(s)
			files[name] = content
			streamServers += strings.Count(content, "set $relay_stream_id")
		}
	} else if len(r.enabledStreams()) > 0 {
		r.fail("streams need the nginx stream module, which this nginx build does not provide")
	}
	files["nginx.conf"] = r.mainConf(streamServers > 0)
	for i := range r.snap.AccessLists {
		al := &r.snap.AccessLists[i]
		if al.BasicAuth.Enabled {
			files["htpasswd/"+safeID(al.ID)] = htpasswd(al)
		}
	}
	return files, r.err()
}

func uniqueName(dir, base, id string, used map[string]bool) string {
	n := fileSafe(base)
	if n == "" {
		n = fileSafe(id)
	}
	name := dir + n + ".conf"
	if used[name] {
		name = dir + n + "-" + fileSafe(id) + ".conf"
	}
	used[name] = true
	return name
}

var fileSafeRe = regexp.MustCompile(`[^a-z0-9._-]+`)

func fileSafe(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "*", "_wildcard")
	s = fileSafeRe.ReplaceAllString(s, "-")
	s = strings.Trim(s, ".-")
	if len(s) > 100 {
		s = s[:100]
	}
	return s
}

var idSafeRe = regexp.MustCompile(`[^a-z0-9_]+`)

// safeID turns an entity id into something usable in zone and variable names.
func safeID(id string) string {
	s := idSafeRe.ReplaceAllString(strings.ToLower(id), "_")
	if s == "" {
		return "x"
	}
	return s
}

// ---------------------------------------------------------------- writer

type writer struct {
	b   strings.Builder
	ind int
}

func (w *writer) l(format string, args ...any) {
	if format == "" {
		w.b.WriteByte('\n')
		return
	}
	w.b.WriteString(strings.Repeat("    ", w.ind))
	if len(args) > 0 {
		fmt.Fprintf(&w.b, format, args...)
	} else {
		w.b.WriteString(format)
	}
	w.b.WriteByte('\n')
}

func (w *writer) open(format string, args ...any) {
	w.l(format+" {", args...)
	w.ind++
}

func (w *writer) close() {
	w.ind--
	w.l("}")
}

func (w *writer) raw(text string) {
	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		if strings.TrimSpace(line) == "" {
			w.b.WriteByte('\n')
			continue
		}
		w.b.WriteString(strings.Repeat("    ", w.ind))
		w.b.WriteString(strings.TrimRight(line, " \t\r"))
		w.b.WriteByte('\n')
	}
}

func (w *writer) String() string { return w.b.String() }

var bareRe = regexp.MustCompile(`^[A-Za-z0-9._~:/?\[\]@!$&()*+,=%^|-]+$`)

// q quotes an nginx argument when needed.
func q(s string) string {
	if s != "" && bareRe.MatchString(s) {
		return s
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", " ", "\r", " ").Replace(s) + `"`
}

// comment sanitises text for a # comment.
func comment(s string) string {
	return strings.NewReplacer("\n", " ", "\r", " ").Replace(s)
}

// ---------------------------------------------------------------- nginx.conf

func (r *renderer) mainConf(streamServers bool) string {
	w := &writer{}
	w.raw(header)
	// Only modules the agent reported as dynamic need load_module; the
	// official nginx image compiles stream, http_v3 and auth_request in.
	loaded := false
	for _, m := range []string{"stream", "geoip2"} {
		if path := r.env.ModulePaths[m]; path != "" && r.mod(m) {
			w.l("load_module %s;", path)
			loaded = true
		}
	}
	if loaded {
		w.l("")
	}
	w.l("user nginx;")
	w.l("worker_processes auto;")
	w.l("worker_rlimit_nofile 65535;")
	w.l("pcre_jit on;")
	w.l("pid %s;", pidFile)
	w.l("error_log %s warn;", r.logPath(ErrorLogFile))
	w.l("error_log stderr warn;")
	w.l("")
	w.open("events")
	w.l("worker_connections 8192;")
	w.l("multi_accept on;")
	w.close()
	w.l("")
	w.open("http")
	w.l("include %s;", mimeTypes)
	w.l("default_type application/octet-stream;")
	w.l("")
	w.l("sendfile on;")
	w.l("tcp_nopush on;")
	w.l("tcp_nodelay on;")
	w.l("server_tokens off;")
	w.l("keepalive_timeout 65s;")
	w.l("types_hash_max_size 2048;")
	w.l("server_names_hash_bucket_size 128;")
	w.l("server_names_hash_max_size 4096;")
	w.l("variables_hash_bucket_size 128;")
	w.l("map_hash_bucket_size 128;")
	w.l("client_max_body_size 1m;")
	w.l("")
	w.l("ssl_session_cache shared:relay_tls:20m;")
	w.l("ssl_session_timeout 1d;")
	w.l("ssl_session_tickets off;")
	w.l("")
	w.l("gzip on;")
	w.l("gzip_vary on;")
	w.l("gzip_proxied any;")
	w.l("gzip_comp_level 5;")
	w.l("gzip_min_length 1024;")
	w.l("gzip_types text/plain text/css text/xml text/javascript application/javascript application/json application/xml application/rss+xml application/atom+xml image/svg+xml font/ttf font/otf;")
	w.l("")
	w.raw(HTTPLogFormat)
	w.l("access_log %s relay_json;", r.logPath(AccessLogFile))
	w.l("")
	w.open("map $http_upgrade $connection_upgrade")
	w.l("default upgrade;")
	w.l("'' close;")
	w.close()
	w.l("")
	w.l("proxy_cache_path %s levels=1:2 keys_zone=relay_assets:32m max_size=1g inactive=30d use_temp_path=off;", cacheDir)
	w.l("")
	w.l("include conf.d/*.conf;")
	w.l("include conf.d/hosts/*.conf;")
	w.l("include conf.d/redirects/*.conf;")
	w.close()
	if r.mod("stream") {
		w.l("")
		w.open("stream")
		w.raw(StreamLogFormat)
		w.l("access_log %s relay_stream_json;", r.logPath(StreamAccessLogFile))
		if !streamServers {
			// The log format references $relay_stream_id; stream servers declare
			// it with `set`, so without any server it must exist another way.
			w.l("")
			w.open("map $protocol $relay_stream_id")
			w.l("default \"\";")
			w.close()
		}
		w.l("")
		w.l("include streams/*.conf;")
		w.close()
	} else {
		w.l("")
		w.l("# The stream block is omitted: the nginx stream module is not available.")
	}
	return w.String()
}

func (r *renderer) logPath(name string) string {
	dir := r.env.LogDir
	if dir == "" {
		dir = "/var/log/relay"
	}
	return strings.TrimRight(dir, "/") + "/" + name
}

